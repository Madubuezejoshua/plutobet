/**
 * Assembles the visual-review artefacts from what the last run actually
 * produced.
 *
 *   node scripts/build-ui-review.mjs
 *
 * Two outputs:
 *
 *   artifacts/ui-review/INTERACTION_AUDIT.md   the per-project rows, merged
 *   artifacts/ui-review/00-contact-sheet.png   labelled thumbnails of every shot
 *
 * BOTH ARE GENERATED, NEVER WRITTEN BY HAND. An audit typed from memory is a
 * claim about what somebody believes happened; these are a record of what the
 * browser did. If a row is missing here, the interaction was not tested.
 *
 * The contact sheet is built with the same headless Chrome the screenshots came
 * from: the thumbnails are laid out as HTML and the page is photographed. That
 * avoids an image library for what is fundamentally a page of pictures with
 * captions, and it means the labels use the same fonts as everything else.
 */
import { spawn } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, join, resolve } from "node:path";

const DIR = resolve(process.cwd(), "artifacts/ui-review");

const CANDIDATE_BROWSERS = [
  "C:/Program Files/Google/Chrome/Application/chrome.exe",
  "C:/Program Files (x86)/Google/Chrome/Application/chrome.exe",
  "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
  "C:/Program Files/Microsoft/Edge/Application/msedge.exe",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium",
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
];

const sleep = (ms) => new Promise((done) => setTimeout(done, ms));

function findBrowser() {
  const found = CANDIDATE_BROWSERS.find((path) => existsSync(path));
  if (!found) throw new Error("No Chrome or Edge found for the contact sheet.");
  return found;
}

// ---------------------------------------------------------------- the audit

function buildAudit() {
  const parts = readdirSync(DIR)
    .filter((name) => name.startsWith("interaction-audit-") && name.endsWith(".md"))
    .sort();

  if (parts.length === 0) {
    console.warn("no per-project audit rows found — run `npx playwright test` first");
    return 0;
  }

  const rows = [];
  for (const part of parts) {
    const project = part.replace("interaction-audit-", "").replace(".md", "");
    const lines = readFileSync(join(DIR, part), "utf8")
      .split("\n")
      .filter((line) => line.trim().startsWith("|"));
    for (const line of lines) rows.push({ project, line });
  }

  const header = [
    "# Interaction audit",
    "",
    "Generated by `scripts/build-ui-review.mjs` from what `e2e/interactions.spec.ts`",
    "did in a real browser, against a review server on a **disposable local",
    "database**. Nothing here is written from reading the source: if a control is",
    "missing from this table, it was not tested.",
    "",
    "`VERIFIED_IN_REAL_BROWSER` means the control was clicked or submitted during",
    "the run that produced this file, and the observed result is what the row says.",
    "A row marked `BLOCKED_BY_KEY` records a control that behaved correctly for an",
    "environment with no provider credentials — the honest fallback, not the",
    "feature.",
    "",
    "| Project | Page | Viewport | Control | Action | Observed result | Route | Status |",
    "|---|---|---|---|---|---|---|---|",
  ];

  /*
   * `line` already begins with its own "|", so the project is prefixed as a
   * complete cell and the rest of the row is appended from that pipe onward.
   * Written as `| ${project} ${line.slice(1)}` it dropped the separator and
   * merged the project into the page cell, leaving every row one column short
   * of the header — which Markdown renders as a quietly shifted table rather
   * than an error.
   */
  const body = rows.map(({ project, line }) => `| ${project} ${line}`);

  writeFileSync(join(DIR, "INTERACTION_AUDIT.md"), [...header, ...body, ""].join("\n"), "utf8");
  return rows.length;
}

// -------------------------------------------------------- the contact sheet

async function buildContactSheet() {
  const shots = readdirSync(DIR)
    .filter((name) => name.endsWith(".png") && name !== "00-contact-sheet.png")
    .sort();

  if (shots.length === 0) {
    console.warn("no screenshots found — run the capture script first");
    return 0;
  }

  /*
   * The images are referenced by `file:` URL rather than inlined as data URIs.
   * Twenty-eight full-page screenshots base64-encoded into one HTML string is
   * tens of megabytes of markup, and Chrome renders it far more slowly than it
   * reads the files from disk.
   */
  const cards = shots
    .map((name) => {
      const label = basename(name, ".png");
      const src = `file:///${join(DIR, name).replace(/\\/g, "/")}`;
      return `<figure><img src="${src}" alt="${label}"><figcaption>${label}</figcaption></figure>`;
    })
    .join("\n");

  const html = `<!doctype html>
<meta charset="utf-8">
<style>
  :root { color-scheme: light; }
  body {
    margin: 0; padding: 28px;
    background: #0d1b2a; color: #e8eef5;
    font: 13px/1.4 "Segoe UI", system-ui, sans-serif;
  }
  h1 { margin: 0 0 4px; font-size: 20px; letter-spacing: -0.02em; }
  p.note { margin: 0 0 24px; color: #8fa3b8; max-width: 70ch; }
  .grid {
    display: grid; gap: 18px;
    grid-template-columns: repeat(auto-fill, minmax(220px, 1fr));
  }
  figure { margin: 0; background: #07111a; border: 1px solid #1b2f44; border-radius: 10px; overflow: hidden; }
  /* Top-aligned and clipped: a full-page shot scaled to fit would make every
     thumbnail an unreadable sliver. The top of the page is what identifies it. */
  img { display: block; width: 100%; height: 300px; object-fit: cover; object-position: top; }
  figcaption { padding: 8px 10px; font-size: 11px; color: #8fa3b8; border-top: 1px solid #1b2f44; }
</style>
<h1>PlutoBet — interface review</h1>
<p class="note">
  ${shots.length} screenshots, desktop and 390&thinsp;px mobile, captured against a
  disposable local database seeded with clearly-labelled demo fixtures. Never
  production, and never the synthetic benchmark fixtures. Thumbnails are cropped
  to the top of each page; open the individual file for the whole thing.
</p>
<div class="grid">
${cards}
</div>`;

  const htmlPath = join(DIR, "contact-sheet.html");
  writeFileSync(htmlPath, html, "utf8");

  const profileDir = await mkdtemp(join(tmpdir(), "plutobet-sheet-"));
  const rows = Math.ceil(shots.length / 5);
  const height = 240 + rows * 360;

  await new Promise((done, fail) => {
    const child = spawn(
      findBrowser(),
      [
        "--headless=new",
        "--disable-gpu",
        "--hide-scrollbars",
        "--no-first-run",
        "--force-device-scale-factor=1",
        // Local files referencing sibling local files.
        "--allow-file-access-from-files",
        `--user-data-dir=${profileDir}`,
        "--virtual-time-budget=15000",
        `--window-size=1280,${height}`,
        `--screenshot=${join(DIR, "00-contact-sheet.png")}`,
        `file:///${htmlPath.replace(/\\/g, "/")}`,
      ],
      { stdio: "ignore", windowsHide: true },
    );
    child.on("exit", () => done(undefined));
    child.on("error", fail);
  });

  await sleep(300);
  return shots.length;
}

async function main() {
  mkdirSync(DIR, { recursive: true });

  const rows = buildAudit();
  const shots = await buildContactSheet();

  console.info(`interaction audit: ${rows} row(s)`);
  console.info(`contact sheet: ${shots} screenshot(s)`);
  if (!existsSync(join(DIR, "00-contact-sheet.png"))) {
    console.error("contact sheet was NOT written");
    process.exit(1);
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
